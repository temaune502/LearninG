#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "../temaune_utils.hpp"

/*
Варіант 14
Розробити програму, за допомогою якої, ввівши відповідний код,
отримуємо для заданого числа його корінь квадратний, квадрат числа,
експоненту числа.
*/

int main(void)
{
    double x = 0.0;
    unsigned int k = 0;

    print("Лабораторна робота №6");    
    print("Програма для обчислення: кореня квадратного, квадрату числа та експоненти заданого числа.");
    
    // Додали підказку для користувача щодо коду операції
    print("Коди операцій: 1 - корінь квадратний, 2 - квадрат числа, 3 - експонента");

    printf("Введіть число: "); 
    if (scanf("%lf", &x) != 1) return 1;

    printf("Введіть код дії (1-3): "); 
    if (scanf("%u", &k) != 1) return 1;

    switch (k) {
        case 1: { // Корінь квадратний
            if (x < 0.0) {
                printf("Помилка: неможливо обчислити корінь квадратний з від'ємного числа.\n");
            } else {
                printf("Корінь квадратний з числа %lf = %lf\n", x, sqrt(x));
            }
        } break;

        case 2: { // Квадрат числа
            printf("Квадрат числа %lf = %lf\n", x, x * x);
        } break;
        
        case 3: { // Експонента числа
            printf("Експонента числа %lf = %lf\n", x, exp(x));
        } break;
        
        default: {
            printf("Помилка: невідомий код дії!\n");
            UNREACHABLE;
        } break;
    }

    return 0;
}